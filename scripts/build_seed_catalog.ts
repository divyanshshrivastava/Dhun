// Compile the works and songs with deterministic UUIDs
export function generateSeedData() {
  const worksList: Array<{ id: string; canonical_title: string }> = [];
  const songsList: Array<{
    id: string;
    work_id: string;
    title: string;
    normalized_title: string;
    aliases: string[];
    artists: string[];
    movie_or_album?: string;
    language: string;
    era: string;
    genres: string[];
    difficulty: string;
  }> = [];

  for (const work of rawCatalog) {
    const workUuid = deterministicUuid(work.workId);
    worksList.push({
      id: workUuid,
      canonical_title: work.canonicalTitle,
    });

    for (let i = 0; i < work.songs.length; i++) {
      const s = work.songs[i];
      const songKey = `${work.workId}-song-${i}-${s.title}`;
      const songUuid = deterministicUuid(songKey);

      // Clean normalized title for fast prefix match
      const normTitle = s.title
        .toLowerCase()
        .replace(/[^a-z0-9\s]/g, '')
        .replace(/\s+/g, ' ')
        .trim();

      songsList.push({
        id: songUuid,
        work_id: workUuid,
        title: s.title,
        normalized_title: normTitle,
        aliases: s.aliases,
        artists: s.artists,
        movie_or_album: s.movieOrAlbum,
        language: s.language,
        era: s.era,
        genres: s.genres,
        difficulty: s.difficulty || 'medium',
      });
    }
  }

  return { works: worksList, songs: songsList };
}


// Deterministic UUID from string key so IDs stay identical across seed runs
function deterministicUuid(inputStr: string): string {
  const hash = crypto.createHash('sha256').update(inputStr).digest('hex');
  return [
    hash.substring(0, 8),
    hash.substring(8, 12),
    '4' + hash.substring(13, 16),
    '8' + hash.substring(17, 20),
    hash.substring(20, 32),
  ].join('-');
}


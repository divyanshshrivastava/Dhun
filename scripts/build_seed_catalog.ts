const targetDir = path.join(process.cwd(), 'src', 'db', 'seed');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const compiled = generateSeedData();
const targetPath = path.join(targetDir, 'songs.json');
fs.writeFileSync(targetPath, JSON.stringify(compiled, null, 2), 'utf-8');
console.log(`Bhai seed catalog generated: ${compiled.works.length} musical works, ${compiled.songs.length} song recordings! Saved to ${targetPath}`);

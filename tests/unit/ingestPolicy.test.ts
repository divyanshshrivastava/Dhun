import { describe, it, expect } from 'vitest';
import { validateIngestPolicy } from '../../scripts/ingest';

describe('Ingest CLI Policy - Synthetic Audio Remote Upload Protection', () => {
  it('permits synthetic tones when storage is local_disk', () => {
    expect(() => validateIngestPolicy('synthetic_tone', 'local_disk', false)).not.toThrow();
  });

  it('refuses synthetic tone upload to Cloudflare R2 by default', () => {
    expect(() => validateIngestPolicy('synthetic_tone', 'cloudflare_r2', false)).toThrowError(
      /Refusing to upload clips generated by SyntheticToneProvider to remote storage/
    );
  });

  it('refuses synthetic tone upload to Supabase Storage by default', () => {
    expect(() => validateIngestPolicy('synthetic_tone', 'supabase_storage', false)).toThrowError(
      /Refusing to upload clips generated by SyntheticToneProvider to remote storage/
    );
  });

  it('permits synthetic tone upload to remote storage when --allow-synthetic-remote is explicitly passed', () => {
    expect(() => validateIngestPolicy('synthetic_tone', 'cloudflare_r2', true)).not.toThrow();
    expect(() => validateIngestPolicy('synthetic_tone', 'supabase_storage', true)).not.toThrow();
  });

  it('permits genuine audio providers (local_files, apple_music) to upload to remote storage without flag', () => {
    expect(() => validateIngestPolicy('local_files', 'cloudflare_r2', false)).not.toThrow();
    expect(() => validateIngestPolicy('apple_music_preview', 'supabase_storage', false)).not.toThrow();
  });
});
